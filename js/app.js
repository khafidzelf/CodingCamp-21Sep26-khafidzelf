window.importData = function(event) {
    const file = event.target.files[0]; if (!file) return;
    const reader = new FileReader();
    reader.onload = function(e) {
        try {
            const imp = JSON.parse(e.target.result);
            if (imp.transactions && imp.categories) {
                transactions = imp.transactions; categories = imp.categories;
                if(imp.notes) notes = imp.notes; if(imp.appSettings) appSettings = imp.appSettings;
                saveData(); alert(dictionary[appSettings.lang].alert_success); window.location.reload();
            } else alert("Invalid JSON!");
        } catch (error) { alert("Error reading file!"); }
    }; reader.readAsText(file);
}
