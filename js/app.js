function renderPagination(totalPages) {
    paginationControls.innerHTML = ''; 
    
    const prevBtn = document.createElement('button');
    prevBtn.innerHTML = '&laquo;';
    prevBtn.className = `px-3 py-1 rounded border text-sm font-semibold transition-colors ${currentPage === 1 ? 'bg-gray-100 text-gray-400 border-gray-200 cursor-not-allowed dark:bg-gray-800 dark:border-gray-700 dark:text-gray-600' : 'bg-white text-gray-700 hover:bg-palette-1 dark:bg-gray-700 dark:text-gray-200 dark:border-gray-600 dark:hover:bg-gray-600 border-gray-300'}`;
    prevBtn.disabled = currentPage === 1;
    prevBtn.onclick = () => { if (currentPage > 1) { currentPage--; renderTransactions(); } };
    paginationControls.appendChild(prevBtn);

    for (let i = 1; i <= totalPages; i++) {
        const pageBtn = document.createElement('button');
        pageBtn.innerText = i;
        pageBtn.className = `px-3 py-1 rounded border text-sm font-semibold transition-colors ${currentPage === i ? 'bg-palette-4 text-white border-palette-4 shadow-sm' : 'bg-white text-gray-700 hover:bg-palette-1 dark:bg-gray-700 dark:text-gray-200 dark:border-gray-600 dark:hover:bg-gray-600 border-gray-300'}`;
        pageBtn.onclick = () => { currentPage = i; renderTransactions(); };
        paginationControls.appendChild(pageBtn);
    }

    const nextBtn = document.createElement('button');
    nextBtn.innerHTML = '&raquo;';
    nextBtn.className = `px-3 py-1 rounded border text-sm font-semibold transition-colors ${currentPage === totalPages ? 'bg-gray-100 text-gray-400 border-gray-200 cursor-not-allowed dark:bg-gray-800 dark:border-gray-700 dark:text-gray-600' : 'bg-white text-gray-700 hover:bg-palette-1 dark:bg-gray-700 dark:text-gray-200 dark:border-gray-600 dark:hover:bg-gray-600 border-gray-300'}`;
    nextBtn.disabled = currentPage === totalPages;
    nextBtn.onclick = () => { if (currentPage < totalPages) { currentPage++; renderTransactions(); } };
    paginationControls.appendChild(nextBtn);
}

function renderTransactions() {
    listElement.innerHTML = '';
    paginationControls.innerHTML = '';

    if (transactions.length === 0) {
        paginationControls.classList.add('hidden');
        return listElement.innerHTML = `<p class="text-center text-gray-500 py-4">${dictionary[appSettings.lang].empty_trans}</p>`;
    }

    const limit = parseInt(limitInput.value);
    const totalPages = Math.ceil(transactions.length / limit);
    
    if (currentPage > totalPages) currentPage = totalPages;
    if (currentPage < 1) currentPage = 1;

    const startIndex = (currentPage - 1) * limit;
    const endIndex = startIndex + limit;

    const sortedData = sortTransactions([...transactions]);
    const paginatedData = sortedData.slice(startIndex, endIndex); 

    paginatedData.forEach(t => {
        const isInc = t.type === 'income'; const color = isInc ? 'text-green-600 dark:text-green-400' : 'text-red-600 dark:text-red-400';
        const sign = isInc ? '+' : '-'; const bg = isInc ? 'bg-palette-2' : 'bg-palette-3';
        const translatedCat = translateCategory(t.category);
        
        const item = document.createElement('div'); item.className = `flex justify-between items-center p-3 mb-2 bg-gray-50 dark:bg-gray-700 rounded-lg shadow-sm border-l-4 ${isInc ? 'border-green-500' : 'border-red-500'}`;
        item.innerHTML = `<div class="flex items-center space-x-4"><div class="${bg} text-white w-10 h-10 rounded-full flex items-center justify-center font-semibold text-sm">${t.name.substring(0, 2).toUpperCase()}</div><div><h4 class="font-semibold text-sm sm:text-base">${t.name}</h4><div class="flex space-x-2 text-xs text-gray-500 dark:text-gray-300"><span class="bg-gray-200 dark:bg-gray-600 px-2 py-0.5 rounded">${translatedCat}</span><span>${t.date}</span></div></div></div><div class="flex items-center space-x-4"><span class="font-semibold ${color}">${sign} ${formatCurrency(t.amount)}</span><button onclick="deleteTransaction(${t.id})" class="bg-red-500 hover:bg-red-700 text-white p-1.5 rounded-md transition">&times;</button></div>`;
        listElement.appendChild(item);
    });

    if (totalPages > 1) {
        paginationControls.classList.remove('hidden');
        renderPagination(totalPages);
    } else {
        paginationControls.classList.add('hidden');
    }
}

