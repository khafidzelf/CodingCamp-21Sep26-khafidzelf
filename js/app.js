function updateCharts() {
    if(appSettings.hideChart) return;
    const exps = transactions.filter(t => t.type === 'outcome'), incs = transactions.filter(t => t.type === 'income');
    
    const expTotals = {}, incTotals = {};
    exps.forEach(t => expTotals[translateCategory(t.category)] = (expTotals[translateCategory(t.category)] || 0) + t.amount); 
    incs.forEach(t => incTotals[translateCategory(t.category)] = (incTotals[translateCategory(t.category)] || 0) + t.amount);
    
    if (expenseChartInstance) expenseChartInstance.destroy(); if (incomeChartInstance) incomeChartInstance.destroy();
    const colors = getThemeColors(), emptyTxt = dictionary[appSettings.lang].empty_chart;
    const renderPie = (ctx, data, col) => new Chart(ctx, { type: 'pie', data: { labels: Object.keys(data).length ? Object.keys(data) : [emptyTxt], datasets: [{ data: Object.keys(data).length ? Object.values(data) : [1], backgroundColor: Object.keys(data).length ? col : ['#E2DFDA'], borderWidth: 1 }] }, options: { plugins: { legend: { position: 'bottom', labels: { color: isDarkMode ? '#e5e7eb' : '#374151' } } } } });
    expenseChartInstance = renderPie(document.getElementById('expenseChart').getContext('2d'), expTotals, colors.out);
    incomeChartInstance = renderPie(document.getElementById('incomeChart').getContext('2d'), incTotals, colors.in);
}
