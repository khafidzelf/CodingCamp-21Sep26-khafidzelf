function formatCurrency(amount) {
    let locale = 'id-ID', curr = 'IDR';
    if (appSettings.currency === 'USD') { locale = 'en-US'; curr = 'USD'; }
    else if (appSettings.currency === 'EUR') { locale = 'de-DE'; curr = 'EUR'; }
    else if (appSettings.currency === 'GBP') { locale = 'en-GB'; curr = 'GBP'; }
    else if (appSettings.currency === 'AUD') { locale = 'en-AU'; curr = 'AUD'; }
    else if (appSettings.currency === 'JPY') { locale = 'ja-JP'; curr = 'JPY'; }
    else if (appSettings.currency === 'KRW') { locale = 'ko-KR'; curr = 'KRW'; }
    else if (appSettings.currency === 'CNY') { locale = 'zh-CN'; curr = 'CNY'; }
    return new Intl.NumberFormat(locale, { style: 'currency', currency: curr, minimumFractionDigits: 0 }).format(amount);
}

