function sortTransactions(data) {
    const sortBy = sortInput.value;
    return data.sort((a, b) => {
        if (sortBy === 'smallest') return a.amount - b.amount;
        if (sortBy === 'largest') return b.amount - a.amount;
        if (sortBy === 'az') return a.name.localeCompare(b.name);
        if (sortBy === 'za') return b.name.localeCompare(a.name);
        if (sortBy === 'oldest') return new Date(a.date) - new Date(b.date);
        return new Date(b.date) - new Date(a.date);
    });
}

sortInput.addEventListener('change', () => { currentPage = 1; renderTransactions(); }); 
